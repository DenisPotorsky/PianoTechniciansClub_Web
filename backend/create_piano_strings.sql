-- Удаляем старую таблицу (если есть)
DROP TABLE IF EXISTS PIANO_STRINGS;

-- Создаём новую таблицу с правильной структурой
CREATE TABLE PIANO_STRINGS (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    brand TEXT NOT NULL,
    model TEXT NOT NULL,
    chor_nummer INTEGER NOT NULL,
    saiten_im_chor INTEGER,
    laenge_mm REAL,
    kern_mm REAL NOT NULL,
    erste_wicklung_mm REAL,
    zweite_wicklung_mm REAL,
    typ TEXT,
    year TEXT
);

-- Создаём индексы для быстрого поиска
CREATE INDEX idx_brand ON PIANO_STRINGS(brand);
CREATE INDEX idx_model ON PIANO_STRINGS(model);
CREATE INDEX idx_chor ON PIANO_STRINGS(chor_nummer);

